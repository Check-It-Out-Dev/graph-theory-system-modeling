"""Render the generated parts of `.agents/` and the per-harness agent shims from their sources.

    PYTHONUTF8=1 python applications/CodeMap/tools/agents/sync_agents.py [--check] [--pack applications/CodeMap/graph/pack]

The skills in `.agents/skills/<name>/SKILL.md` are written by hand and are the single source of
truth. Everything below is generated, so edit the source and run this script, never the output:

- `.claude/agents/<agent>.md`: Claude Code subagent shims (Cursor and VS Code read the same folder).
  Frontmatter from the skill; the body tells the agent which files to read first.
- `.agents/skills/ladybug-graph/references/tools.md`: the grammar and pack tool contract, from
  `remote/engine_mcp.py`, `graph/delta/pack_mcp.py` and `app/dsl.py` (Hypatia and Grothendieck).
- `.agents/skills/ladybug-graph/references/schema.md`: tables, columns, edge kinds and counts, read
  from the pack database (needs the pack).
- `.agents/skills/erdos-architect/references/tools.md`: the direct graph tool, from `remote/ladybug_mcp.py`.
- `.agents/skills/erdos-architect/references/topology.md`: repositories, layers, edge kinds, hubs and
  coupling, counted from the pack database through the same tool Erdős uses (needs the pack).
- `.agents/skills/erdos-architect/references/graph-map.md`: the system summary, the L1 index, every L2
  navigator in full and the curation notes, as XML, with membership measured from the database (needs the pack).
- `.agents/skills/erdos-architect/CLAUDE.erdos.md`: Erdős's operating manual, the SKILL.md body with every
  `<include file="references/..."/>` line replaced by that file. A harness delivers it as a CLAUDE.md (needs the pack).

`--check` renders in memory and exits 1 when a committed file differs; outputs that need the pack
are skipped (and reported) when the pack is absent. Deterministic: same inputs, same bytes.
"""

