COMMENT = re.compile(r"<!--.*?-->[ \t]*\n?", re.S)
INCLUDE = re.compile(r'^[ \t]*<include file="(references/[A-Za-z0-9_.-]+\.md)"\s*/>[ \t]*$', re.M)

