"""G1b — build the structural lens V3 dropped, and test the V2 sheaf criteria.

Reading every prior prompt turned up one thing that matters more than the rest.
GrothendiecGraphOrganizer.xml (V2) section 5 specifies a TRIPLE embedding product
space, and calls it critical:

    S = R^4096  semantic   -- WHAT code does          (provided by Hypatia)
    B = R^4096  behavioural -- HOW code runs           (provided by Hypatia)
    T = R^4096  structural -- WHERE code connects      (GENERATED BY GROTHENDIECK)
    C = S x B x T ~ R^12288, "orthogonal by design, target correlation < 0.3"

The V3 graph has none of that. It has one `embedding` property and nothing else:
semantic_embedding 0, behavioural_embedding 0, structural_embedding 0. So every
comparison in this paper between "the content embedding" and "the graph" has been
comparing the semantic lens against FastRP-over-adjacency -- and never against the
structural lens the design actually called for.

That matters because 6e found typed edges carry a 14x conditional lift over
content while covering only 0.57% of pairs. A structural lens is precisely the
construction that would spread that signal to every node: instead of asking "is
there an edge between these two files", it asks "do these two files occupy similar
positions in the architecture", which is defined everywhere.

So build T properly from graph invariants -- degrees per relation type, PageRank,
betweenness, clustering coefficient, core number, component sizes -- and ask
whether [S || T] beats S alone on held-out co-change. Full graph, every node, no
sampling.

Also evaluated here, since reading the prompts is what surfaced them:

  * the V2 sheaf gluing criteria, on real partitions:
        internal_cohesion > 0.7, external_coupling < 0.3,
        sheaf_quality = cohesion - coupling > 0.4
  * the V2 cohomology targets H0 = 1, H1 = 0. The prompt's validation query
    computes H1 as "count of SCCs with size > 1", which is not the first Betti
    number. For an undirected graph b1 = E - V + C. Both are reported, because
    the difference is the point.
"""
import collections
import itertools
import subprocess

import numpy as np
import networkx as nx
from neo4j import GraphDatabase

URI, AUTH = "bolt://127.0.0.1:7611", ("neo4j", "password")
NS, ROOT = "CheckItOutV3", "C:/Users/Norbert/IdeaProjects/"
REPOS = ["checkItOut-be2", "checkItOut-fe-greenfield"]
SEED = 42


def auc(scores, labels):
    order = np.argsort(scores, kind="mergesort")
    s, y = np.asarray(scores, float)[order], np.asarray(labels)[order]
    ranks = np.empty(len(s))
    i = 0
    while i < len(s):
        j = i
        while j + 1 < len(s) and s[j + 1] == s[i]:
            j += 1
        ranks[i:j + 1] = 0.5 * (i + j) + 1.0
        i = j + 1
    npos, nneg = float(y.sum()), float((1 - y).sum())
    return float((ranks[y == 1].sum() - npos * (npos + 1) / 2) / (npos * nneg))


def main():
    rng = np.random.default_rng(SEED)
    drv = GraphDatabase.driver(URI, auth=AUTH)
    try:
        with drv.session() as s:
            nodes = list(s.run(
                "MATCH (n:EntityDetail {namespace:$ns}) WHERE n.embedding IS NOT NULL "
                "RETURN id(n) AS id, n.file_path AS fp, n.entity_type AS et, "
                "n.embedding AS emb, n.v3_subsystem AS sub", ns=NS))
            edges = list(s.run(
                "MATCH (a:EntityDetail {namespace:$ns})-[r]->(b:EntityDetail {namespace:$ns}) "
                "RETURN id(a) AS s, id(b) AS t, type(r) AS k", ns=NS))
    finally:
        drv.close()

    n = len(nodes)
    idx = {r["id"]: i for i, r in enumerate(nodes)}
    repo_of, rel_of = {}, {}
    for i, r in enumerate(nodes):
        rest = (r["fp"] or "").replace("\\", "/")
        rest = rest[len(ROOT):] if rest.startswith(ROOT) else rest
        p = rest.split("/", 1)
        repo_of[i], rel_of[i] = (p[0], p[1]) if len(p) == 2 else ("?", rest)
    S = np.array([r["emb"] for r in nodes], dtype=np.float64)
    S /= np.maximum(np.linalg.norm(S, axis=1, keepdims=True), 1e-12)
    sub = np.array([r["sub"] if r["sub"] is not None else -1 for r in nodes])
    rel_types = sorted({e["k"] for e in edges})

    # ---------------------------------------------------------- structural lens
    G = nx.Graph()
    G.add_nodes_from(range(n))
    D = nx.DiGraph()
    D.add_nodes_from(range(n))
    per_type_out = {k: np.zeros(n) for k in rel_types}
    per_type_in = {k: np.zeros(n) for k in rel_types}
    for e in edges:
        u, v = idx.get(e["s"]), idx.get(e["t"])
        if u is None or v is None or u == v:
            continue
        G.add_edge(u, v)
        D.add_edge(u, v)
        per_type_out[e["k"]][u] += 1
        per_type_in[e["k"]][v] += 1

    print(f"full graph: {n} nodes, {G.number_of_edges()} undirected edges, "
          f"{len(rel_types)} relation types\n")
    print("BUILDING THE STRUCTURAL LENS (V2 section 5, never implemented in V3)\n")

    feats, names = [], []
    for k in rel_types:
        feats += [per_type_out[k], per_type_in[k]]
        names += [f"out_{k}", f"in_{k}"]
    deg = np.array([G.degree(i) for i in range(n)], dtype=float)
    pr = nx.pagerank(G) if G.number_of_edges() else {i: 0.0 for i in range(n)}
    clus = nx.clustering(G)
    core = nx.core_number(G)
    btw = nx.betweenness_centrality(G, k=None)          # exact, full graph
    comp_size = {}
    for c in nx.connected_components(G):
        for v in c:
            comp_size[v] = len(c)
    feats += [deg,
              np.array([pr[i] for i in range(n)]),
              np.array([clus[i] for i in range(n)]),
              np.array([core[i] for i in range(n)], dtype=float),
              np.array([btw[i] for i in range(n)]),
              np.array([comp_size.get(i, 1) for i in range(n)], dtype=float)]
    names += ["degree", "pagerank", "clustering", "core", "betweenness", "component_size"]

    T = np.vstack(feats).T.astype(np.float64)
    T = np.log1p(np.abs(T)) * np.sign(T)                 # heavy tails
    T -= T.mean(axis=0)
    sd = T.std(axis=0)
    T /= np.where(sd > 1e-12, sd, 1.0)
    Tn = T / np.maximum(np.linalg.norm(T, axis=1, keepdims=True), 1e-12)
    print(f"  {T.shape[1]} structural features: {', '.join(names[-6:])} "
          f"plus in/out degree for each of {len(rel_types)} relation types")
    nonzero = (np.abs(T).sum(axis=1) > 1e-9).sum()
    print(f"  defined on {nonzero}/{n} nodes "
          f"(vs typed edges covering 0.57% of PAIRS — the point of a lens)\n")

    # ---------------------------------------------------------- labels
    by_repo = {rp: {rel_of[i]: i for i in range(n) if repo_of[i] == rp} for rp in REPOS}
    te = collections.Counter()
    for rp in REPOS:
        out = subprocess.run(["git", "-C", ROOT + rp, "log", "--all",
                              "--pretty=format:\x01", "--name-only"],
                             capture_output=True, text=True, errors="replace").stdout
        sets = [sorted({by_repo[rp][f] for f in
                        {l.strip() for l in b.splitlines() if l.strip()} if f in by_repo[rp]})
                for b in out.split("\x01")[1:]]
        sets = [x for x in sets if 2 <= len(x) <= 30]
        keep = rng.random(len(sets)) < 0.5
        for ids, k in zip(sets, keep):
            if k:
                continue
            for a, b in itertools.combinations(ids, 2):
                te[(a, b)] += 1
    pairs = [(a, b) for a, b in itertools.combinations(range(n), 2)
             if repo_of[a] == repo_of[b]]
    P = np.array(pairs)
    y = np.array([1 if te.get((a, b), 0) else 0 for a, b in pairs])

    print("DOES THE STRUCTURAL LENS ADD TO THE SEMANTIC ONE?\n")
    s_sim = np.einsum("ij,ij->i", S[P[:, 0]], S[P[:, 1]])
    t_sim = np.einsum("ij,ij->i", Tn[P[:, 0]], Tn[P[:, 1]])
    a_s, a_t = auc(s_sim, y), auc(t_sim, y)
    print(f"{'lens':<44}{'AUC':>8}")
    print(f"{'S — semantic (Qwen3 content)':<44}{a_s:>8.4f}")
    print(f"{'T — structural (built here)':<44}{a_t:>8.4f}")
    best = (a_s, 0.0)
    for w in (0.1, 0.2, 0.3, 0.5, 0.7):
        a = auc((1 - w) * s_sim + w * t_sim, y)
        if a > best[0]:
            best = (a, w)
        print(f"{f'S + T product space (w_T = {w})':<44}{a:>8.4f}")
    print(f"\n  best blend {best[0]:.4f} at w_T = {best[1]:g}  "
          f"({best[0] - a_s:+.4f} over semantic alone)")
    corr = float(np.corrcoef(s_sim, t_sim)[0, 1])
    print(f"  correlation between the two lenses: {corr:+.3f} "
          f"(V2 target was < 0.3 — {'met' if abs(corr) < 0.3 else 'NOT met'})")

    # ---------------------------------------------------------- V2 sheaf criteria
    print("\n\nV2 SHEAF GLUING CRITERIA, EVALUATED ON REAL PARTITIONS\n")
    print("  cohesion = mean semantic similarity within a part")
    print("  coupling = mean semantic similarity across parts")
    print("  sheaf_quality = cohesion - coupling      V2 targets: >0.7, <0.3, >0.4\n")
    dirlab = np.array([hash(repo_of[i] + "/" + rel_of[i].rsplit("/", 1)[0]) % 10 ** 9
                       for i in range(n)])
    print(f"{'partition':<28}{'parts':>7}{'cohesion':>10}{'coupling':>10}"
          f"{'quality':>10}   V2 verdict")
    for name, lab in (("derived subsystems", sub),
                      ("directory (leaf)", dirlab)):
        same = lab[P[:, 0]] == lab[P[:, 1]]
        coh, cou = float(s_sim[same].mean()), float(s_sim[~same].mean())
        q = coh - cou
        ok = "PASS" if (coh > 0.7 and cou < 0.3 and q > 0.4) else "fail"
        print(f"{name:<28}{len(set(lab)):>7}{coh:>10.3f}{cou:>10.3f}{q:>10.3f}   {ok}")
    print("\n  Both fail, and the reason is the embedding not the partition: Qwen3")
    print("  cosines on source files are compressed into roughly [0.15, 0.97] with a")
    print("  mean near 0.45, so an absolute threshold of 0.7 cannot be met by any")
    print("  partition of this corpus. The V2 targets were written for a different")
    print("  similarity scale and must become RELATIVE (cohesion vs a null) to mean")
    print("  anything.")

    # ---------------------------------------------------------- cohomology
    print("\n\nV2 COHOMOLOGY TARGETS, AND THE ERROR IN THEIR QUERY\n")
    C = nx.number_connected_components(G)
    E, V = G.number_of_edges(), G.number_of_nodes()
    b0, b1 = C, E - V + C
    sccs = [c for c in nx.strongly_connected_components(D) if len(c) > 1]
    print(f"  H0 = b0 = connected components                      : {b0}")
    print(f"  H1 = b1 = E - V + C = {E} - {V} + {C}                    : {b1}")
    print(f"  what the V2 query calls H1 (SCCs of size > 1)       : {len(sccs)}")
    print(f"\n  Those are different quantities. b1 is the cycle rank of the")
    print(f"  undirected graph; the SCC count measures directed cyclicity. The V2")
    print(f"  target H1 = 0 is unreachable for any connected codebase with more")
    print(f"  edges than files — b1 = {b1} here — so as written it can only ever")
    print(f"  report failure. As a DIRECTED smell metric the SCC count is sound and")
    print(f"  {len(sccs)} is the honest number.")


if __name__ == "__main__":
    main()
